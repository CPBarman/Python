#------------------------------------------------------------------------------------------------#
# Arithmetic Operators
# Operator       Name                    Example
#   +            Addition                a + b
#   -            Subtraction             a - b
#   *            Multiplication          a * b
#   /            Division                a / b
#   //           Floor Division           a // b
#   %            Modulus (Remainder)     a % b
#   **           Exponentiation          a ** b
#------------------------------------------------------------------------------------------------#

#Example-1 [Addition]
x = 2
y = 3
result = x + y
print(result)

#Example-2 [Subtraction]
x = 4
y = 6
result = y - x
print(result)

#Example-3 [ Multiplication]
x = 3
y = 2
result = x * y
print(result)

#Example-4 [Division]
x = 6
y = 2
result = x / y
print(result)

#Example-5 [Floor Division ]
x = 10
