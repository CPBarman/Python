#================================================================================================#
#                                  Assignment Operators

# Assignment operators are used to assign a value to a variable
#
# =    → Assigns a value to a variable
# +=   → Adds a value to a variable and assigns the result
# -=   → Subtracts a value from a variable and assigns the result
# *=   → Multiplies a variable by a value and assigns the result
# /=   → Divides a variable by a value and assigns the result
# %=   → Assigns the remainder to a variable
# **=  → Raises a variable to a power and assigns the result
# //=  → Performs floor division and assigns the result
#================================================================================================#




#------------------------------------------------------------------------------------------------#
# Structure-1: Simple Assignment Operator
# <variable> = <value>
#------------------------------------------------------------------------------------------------#

# Example-1
x = 10
print(x)

# Output:
# 10




#------------------------------------------------------------------------------------------------#
# Structure-2: Addition Assignment Operator
# <variable> += <value>
#------------------------------------------------------------------------------------------------#

# Example-2
x = 10
x += 5
print(x)

# Output:
# 15




#------------------------------------------------------------------------------------------------#
# Structure-3: Subtraction Assignment Operator
# <variable> -= <value>
#------------------------------------------------------------------------------------------------#

# Example-3
x = 10
x -= 5
print(x)

# Output:
# 5




#------------------------------------------------------------------------------------------------#
# Structure-4: Multiplication Assignment Operator
# <variable> *= <value>
#------------------------------------------------------------------------------------------------#

# Example-4
x = 10
x *= 5
print(x)

# Output:
# 50




#------------------------------------------------------------------------------------------------#
# Structure-5: Division Assignment Operator
# <variable> /= <value>
#------------------------------------------------------------------------------------------------#

# Example-5
x = 10
x /= 5
print(x)

# Output:
# 2.0




#------------------------------------------------------------------------------------------------#
# Structure-6: Modulus Assignment Operator
# <variable> %= <value>
#------------------------------------------------------------------------------------------------#

# Example-6
x = 10
x %= 3
print(x)

# Output:
# 1




#------------------------------------------------------------------------------------------------#
# Structure-7: Exponentiation Assignment Operator
# <variable> **= <value>
#------------------------------------------------------------------------------------------------#

# Example-7
x = 2
x **= 3
print(x)

# Output:
# 8




#------------------------------------------------------------------------------------------------#
# Structure-8: Floor Division Assignment Operator
# <variable> //= <value>
#------------------------------------------------------------------------------------------------#

# Example-8
x = 10
x //= 3
print(x)

# Output:
# 3




#------------------------------------------------------------------------------------------------#
# Structure-9: Multiple Assignment
# <variable1>, <variable2> = <value1>, <value2>
#------------------------------------------------------------------------------------------------#

# Example-9
x, y = 10, 20
print(x)
print(y)

# Output:
# 10
# 20




#------------------------------------------------------------------------------------------------#
# Structure-10: Assigning the Same Value to Multiple Variables
# <variable1> = <variable2> = <value>
#------------------------------------------------------------------------------------------------#

# Example-10
x = y = z = 10
print(x)
print(y)
print(z)

# Output:
# 10
# 10
# 10

