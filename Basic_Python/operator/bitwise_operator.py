#================================================================================================#
#                                  Bitwise Operators

# Bitwise operators are used to perform operations on the binary representation of numbers
#
# &    → Bitwise AND
# |    → Bitwise OR
# ^    → Bitwise XOR
# ~    → Bitwise NOT
# <<   → Left Shift
# >>   → Right Shift
#================================================================================================#




#------------------------------------------------------------------------------------------------#
# Structure-1: Bitwise AND Operator
# <value1> & <value2>
#------------------------------------------------------------------------------------------------#

# Example-1
x = 5
y = 3
print(x & y)

# Binary:
# 5 = 101
# 3 = 011
# --------
#     001

# Output:
# 1




#------------------------------------------------------------------------------------------------#
# Structure-2: Bitwise OR Operator
# <value1> | <value2>
#------------------------------------------------------------------------------------------------#

# Example-2
x = 5
y = 3
print(x | y)

# Binary:
# 5 = 101
# 3 = 011
# --------
#     111

# Output:
# 7




#------------------------------------------------------------------------------------------------#
# Structure-3: Bitwise XOR Operator
# <value1> ^ <value2>
#------------------------------------------------------------------------------------------------#

# Example-3
x = 5
y = 3
print(x ^ y)

# Binary:
# 5 = 101
# 3 = 011
# --------
#     110

# Output:
# 6




#------------------------------------------------------------------------------------------------#
# Structure-4: Bitwise NOT Operator
# ~<value>
#------------------------------------------------------------------------------------------------#

# Example-4
x = 5
print(~x)

# Binary:
# 5  = 00000101
# ~5 = 11111010

# Output:
# -6




#------------------------------------------------------------------------------------------------#
# Structure-5: Left Shift Operator
# <value> << <number_of_positions>
#------------------------------------------------------------------------------------------------#

# Example-5
x = 5
print(x << 1)

# Binary:
# 5       = 101
# 5 << 1  = 1010

# Output:
# 10




#------------------------------------------------------------------------------------------------#
# Structure-6: Right Shift Operator
# <value> >> <number_of_positions>
#------------------------------------------------------------------------------------------------#

# Example-6
x = 10
print(x >> 1)

# Binary:
# 10      = 1010
# 10 >> 1 = 0101

# Output:
# 5




#------------------------------------------------------------------------------------------------#
# Structure-7: Bitwise AND Assignment Operator
# <variable> &= <value>
#------------------------------------------------------------------------------------------------#

# Example-7
