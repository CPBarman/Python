#------------------------------------------------------------------------------------------------#
# Relational Operators
# Operator       Name                            Example
#   >            Greater Than                    a > b
#   <            Less Than                       a < b
#   >=           Greater Than or Equal To       a >= b
#   <=           Less Than or Equal To          a <= b
#   ==           Equal To                        a == b
#   !=           Not Equal To                    a != b
#
#------------------------------------------------------------------------------------------------#

# Example-1: [Greater Than Operator (>)]
x = 3
y = 2
result = x > y
print(result)

# Example-1: [Less Than Operator (<)]
x = 4
y = 3
result = x > y
print(result)

# Example-3: [Greater Than or Equal To Operator (>=)]
x = 2
y = 2
result = x >= y
print(result)

# Example-4: [Less Than or Equal To Operator (<=)]
x = 2
y = 3
result = x <= y
print(result)

# Example-5: [Equal To Operator (==)]
x = 4
y = 4
result = x == y
print(result)

# Example-5: [Not Equal To Operator (==)]
x = 2
y = 4
result = x != y
print(result)