#------------------------------------------------------------------------------------------------#
# Structure-1: for loop with range(stop)
# for variable in range(value):
#    <statement>
#------------------------------------------------------------------------------------------------#

#Example-1
for i in range(5):
    print("Hello")

#Example-2
for i in range(5):
    print(i)

#Example-3
for i in range(10):
    print(i)


#------------------------------------------------------------------------------------------------#
# Structure-2: for loop with range(start, stop)
# for variable in range(start, stop):
#    <statement>
#------------------------------------------------------------------------------------------------#

#Example-1
for i in range(1,6):
    print(i)

#Example-2
for i in range(2,6):
    print(i)


#------------------------------------------------------------------------------------------------#
#  Structure-3: for loop with range(start, stop, step)
# for variable in range range(start, stop):
#    <statement>
#------------------------------------------------------------------------------------------------#

#Example-1
for i in range(2,6,1):
    print(i)

#Example-2
for i in range(2,6,3):
    print(i)
