#================================================================================================#
#                                 Basic Mathematical Functions
# np.sqrt()
# np.square()
# np.power()
# np.abs()
#================================================================================================#
# NumPy provides various mathematical functions to perform
# mathematical operations efficiently on NumPy arrays.


#------------------------------------------------------------------------------------------------#
# Structure-1: Square Root
#------------------------------------------------------------------------------------------------#
# np.sqrt(array)
#
# Returns the square root of each element in the array.
#------------------------------------------------------------------------------------------------#
import numpy as np
arr = np.array([1, 4, 9, 16, 25])
result = np.sqrt(arr)
print(result)

# Output:
# [1. 2. 3. 4. 5.]


#------------------------------------------------------------------------------------------------#
# Structure-2: Square
#------------------------------------------------------------------------------------------------#
# np.square(array)
#
# Returns the square of each element in the array.
#------------------------------------------------------------------------------------------------#

import numpy as np
arr = np.array([1, 2, 3, 4, 5])
result = np.square(arr)
print(result)

# Output:
# [ 1  4  9 16 25]


#------------------------------------------------------------------------------------------------#
# Structure-3: Power
#------------------------------------------------------------------------------------------------#
# np.power(array, exponent)
#
# Raises each element of the array to the specified power.
#------------------------------------------------------------------------------------------------#

import numpy as np
arr = np.array([1, 2, 3, 4])
result = np.power(arr, 3)
print(result)

# Output:
# [ 1  8 27 64]


#------------------------------------------------------------------------------------------------#
# Structure-4: Absolute Value
#------------------------------------------------------------------------------------------------#
# np.abs(array)
#
# Returns the absolute value of each element in the array.
#------------------------------------------------------------------------------------------------#

import numpy as np
arr = np.array([-10, -5, 0, 5, 10])
result = np.abs(arr)
print(result)

# Output:
# [10  5  0  5 10]

