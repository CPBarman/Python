#================================================================================================#
#                                 Basic Mathematical Functions
# np.sqrt()
# np.square()
# np.power()
# np.abs()
#================================================================================================#
# NumPy provides various mathematical functions to perform
# mathematical operations efficiently on NumPy arrays.


#------------------------------------------------------------------------------------------------#
# Structure-1: Square Root
#------------------------------------------------------------------------------------------------#
# np.sqrt(array)
#
# Returns the square root of each element in the array.
#------------------------------------------------------------------------------------------------#
import numpy as np
arr = np.array([1, 4, 9, 16, 25])
result = np.sqrt(arr)
print(result)

# Output:
# [1. 2. 3. 4. 5.]


#------------------------------------------------------------------------------------------------#
# Structure-2: Square
#------------------------------------------------------------------------------------------------#
# np.square(array)
#
# Returns the square of each element in the array.
#------------------------------------------------------------------------------------------------#

import numpy as np
arr = np.array([1, 2, 3, 4, 5])
result = np.square(arr)
print(result)

# Output:
# [ 1  4  9 16 25]


#------------------------------------------------------------------------------------------------#
# Structure-3: Power
#------------------------------------------------------------------------------------------------#
# np.power(array, exponent)
#
# Raises each element of the array to the specified power.
#------------------------------------------------------------------------------------------------#

import numpy as np
arr = np.array([1, 2, 3, 4])
result = np.power(arr, 3)
print(result)

# Output:
# [ 1  8 27 64]


#------------------------------------------------------------------------------------------------#
# Structure-4: Absolute Value
#------------------------------------------------------------------------------------------------#
# np.abs(array)
#
# Returns the absolute value of each element in the array.
#------------------------------------------------------------------------------------------------#

import numpy as np
arr = np.array([-10, -5, 0, 5, 10])
result = np.abs(arr)
print(result)

# Output:
# [10  5  0  5 10]


#------------------------------------------------------------------------------------------------#
# Structure-5: Exponential
#------------------------------------------------------------------------------------------------#
# np.exp(array)
#
# Calculates e^x for each element of the array.
#------------------------------------------------------------------------------------------------#

import numpy as np
arr = np.array([0, 1, 2, 3])
result = np.exp(arr)
print(result)


#------------------------------------------------------------------------------------------------#
# Structure-6: Natural Logarithm
#------------------------------------------------------------------------------------------------#
# np.log(array)
#
# Calculates the natural logarithm (base e) of each element.
#------------------------------------------------------------------------------------------------#

import numpy as np
arr = np.array([1, np.e, np.e**2])
result = np.log(arr)
print(result)

# Output:
# [0. 1. 2.]


#------------------------------------------------------------------------------------------------#
# Structure-7: Base-10 Logarithm
#------------------------------------------------------------------------------------------------#
# np.log10(array)
#
# Calculates the base-10 logarithm of each element.
#------------------------------------------------------------------------------------------------#

import numpy as np
arr = np.array([1, 10, 100, 1000])
result = np.log10(arr)
print(result)

# Output:
# [0. 1. 2. 3.]


#------------------------------------------------------------------------------------------------#
# Structure-8: Sine
#------------------------------------------------------------------------------------------------#
# np.sin(array)
#
# Calculates the sine of each element.
# Angles must be given in radians.
#------------------------------------------------------------------------------------------------#

import numpy as np
arr = np.array([0, np.pi / 2, np.pi])
result = np.sin(arr)
print(result)

# Output:
# [0.0000000e+00 1.0000000e+00 1.2246468e-16]

#------------------------------------------------------------------------------------------------#
# Structure-9: Cosine
#------------------------------------------------------------------------------------------------#
# np.cos(array)
#
# Calculates the cosine of each element.
# Angles must be given in radians.
#------------------------------------------------------------------------------------------------#

import numpy as np
arr = np.array([0, np.pi / 2, np.pi])
result = np.cos(arr)
print(result)

# Output:
# [ 1.000000e+00  6.123234e-17 -1.000000e+00]

#------------------------------------------------------------------------------------------------#
# Structure-10: Tangent
#------------------------------------------------------------------------------------------------#
# np.tan(array)
#
# Calculates the tangent of each element.
# Angles must be given in radians.
#------------------------------------------------------------------------------------------------#

import numpy as np
arr = np.array([0, np.pi / 4])
result = np.tan(arr)
