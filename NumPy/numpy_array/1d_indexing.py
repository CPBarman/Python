# Structure-1: Accessing an Element of a 1D Array Using Index
# <array_name>[<index>]
#------------------------------------------------------------------------------------------------#

# Example-1
import numpy as np
numbers = np.array([10, 20, 30, 40, 50])
print(numbers[0])
print(numbers[2])
print(numbers[4])

# Output:
# 10
# 30
# 50

#Example-2
