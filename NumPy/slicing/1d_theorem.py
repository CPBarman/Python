#------------------------------------------------------------------------------------------------#
# Structure-1: Slicing a 1D NumPy Array
# <array_name>[<start>:<stop>]
#------------------------------------------------------------------------------------------------#

# Example
import numpy as np
numbers = np.array([10, 20, 30, 40, 50])
print(numbers[1:4])

# Output:
# [20 30 40]


#------------------------------------------------------------------------------------------------#
# Structure-2: Slicing from a Specific Start Index
# <array_name>[<start>:]
#------------------------------------------------------------------------------------------------#

# Example
numbers = np.array([10, 20, 30, 40, 50])
print(numbers[2:])

# Output:
# [30 40 50]

#------------------------------------------------------------------------------------------------#
# Structure-3: Slicing Up to a Specific Stop Index
# <array_name>[:<stop>]
#------------------------------------------------------------------------------------------------#

# Example
numbers = np.array([10, 20, 30, 40, 50])
print(numbers[:3])

# Output:
# [10 20 30]


#------------------------------------------------------------------------------------------------#
# Structure-4: Slicing with Start, Stop and Step
# <array_name>[<start>:<stop>:<step>]
#------------------------------------------------------------------------------------------------#

# Example
numbers = np.array([10, 20, 30, 40, 50, 60])
print(numbers[0:6:2])

# Output:
# [10 30 50]


#------------------------------------------------------------------------------------------------#
# Structure-5: Slicing Using Negative Index
# <array_name>[<negative_start>:<negative_stop>]
#------------------------------------------------------------------------------------------------#

# Example
numbers = np.array([10, 20, 30, 40, 50])
print(numbers[-4:-1])

# Output:
# [20 30 40]


#------------------------------------------------------------------------------------------------#
# Structure-6: Reversing a NumPy Array Using Slicing
# <array_name>[::-1]
#------------------------------------------------------------------------------------------------#

# Example
numbers = np.array([10, 20, 30, 40, 50])
print(numbers[::-1])

# Output:
# [50 40 30 20 10]
