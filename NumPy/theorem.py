# Example-1
import numpy as np
numbers = np.array([10, 20, 30, 40, 50])
print(numbers)               #[10 20 30 40 50]


# Example-2: Checking the Type of a NumPy Array
import numpy as np
numbers = np.array([10, 20, 30, 40, 50])
print(type(numbers))          #<class 'numpy.ndarray'>

