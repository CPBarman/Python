#------------------------------------------------------------------------------------------------#
# Structure-1: Basic Slicing
# <sequence>[<start>:<stop>]
#------------------------------------------------------------------------------------------------#

# Example-1
numbers = [10, 20, 30, 40, 50]
print(numbers[1:4])     #[20, 30, 40]


#------------------------------------------------------------------------------------------------#
# Structure-2: Slicing from Beginning
# <sequence>[:<stop>]
#------------------------------------------------------------------------------------------------#

# Example
numbers = [10, 20, 30, 40, 50]
print(numbers[:3])         #[10, 20, 30]


#------------------------------------------------------------------------------------------------#
# Structure-3: Slicing to the End
# <sequence>[<start>:]
#------------------------------------------------------------------------------------------------#

# Example
numbers = [10, 20, 30, 40, 50]
print(numbers[2:])          #[30, 40, 50]


#------------------------------------------------------------------------------------------------#
# Structure-4: Slicing with Step
# <sequence>[<start>:<stop>:<step>]
#------------------------------------------------------------------------------------------------#

# Example
numbers = [10, 20, 30, 40, 50]
print(numbers[0:5:2])         #[10, 30, 50]


#------------------------------------------------------------------------------------------------#
# Structure-5: Negative Index Slicing
# <sequence>[-<start>:-<stop>]
#------------------------------------------------------------------------------------------------#

# Example
numbers = [10, 20, 30, 40, 50]
print(numbers[-4:-1])            #[20, 30, 40]



#------------------------------------------------------------------------------------------------#
# Structure-6: Reverse Slicing
# <sequence>[<start>:<stop>:-<step>]
#------------------------------------------------------------------------------------------------#

# Example
numbers = [10, 20, 30, 40, 50]
print(numbers[4:1:-1])          #[50, 40, 30]


#------------------------------------------------------------------------------------------------#
# Structure-7: Reversing a Sequence Using Slicing
# <sequence>[::-1]
#------------------------------------------------------------------------------------------------#

# Example
numbers = [10, 20, 30, 40, 50]
print(numbers[::-1])              #[50, 40, 30, 20, 10]



