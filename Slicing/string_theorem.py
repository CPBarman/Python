#------------------------------------------------------------------------------------------------#
# Structure-1: Basic String Slicing
# <string>[<start>:<stop>]
#------------------------------------------------------------------------------------------------#

# Example
word = "Python"
print(word[0:4])                   #Pyth

#------------------------------------------------------------------------------------------------#
# Structure-2: String Slicing from Beginning
# <string>[:<stop>]
#------------------------------------------------------------------------------------------------#

# Example
word = "Python"
print(word[:3])                   #Pyt

#------------------------------------------------------------------------------------------------#
# Structure-3: String Slicing to the End
# <string>[<start>:]
#------------------------------------------------------------------------------------------------#

# Example
word = "Python"
print(word[2:])                  #thon


#------------------------------------------------------------------------------------------------#
# Structure-4: String Slicing with Step
# <string>[<start>:<stop>:<step>]
#------------------------------------------------------------------------------------------------#

# Example
word = "Python"
print(word[0:6:2])                #Pto

#------------------------------------------------------------------------------------------------#
# Structure-5: Negative Index Slicing in String
# <string>[-<start>:-<stop>]
#------------------------------------------------------------------------------------------------#

# Example
word = "Python"
print(word[-4:-1])               #tho


#------------------------------------------------------------------------------------------------#
# Structure-6: Reversing a String Using Slicing
# <string>[::-1]
#------------------------------------------------------------------------------------------------#

# Example
word = "Python"
print(word[::-1])                #nohtyP

